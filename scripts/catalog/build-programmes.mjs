// Generates supabase/migrations/20261118130040_fitx_training_programmes_seed.sql from src/data/programmes.
// Usage: node scripts/catalog/build-programmes.mjs [--check]
// --check exits 1 when the committed migration differs from what the data produces.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { PROGRAMMES } from "../../src/data/programmes/index.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const PROGRAMME_SEED_MIGRATION = path.join(ROOT, "supabase/migrations/20261118130040_fitx_training_programmes_seed.sql");
export { PROGRAMMES };

/** The seed migration for the given programmes. */
export function programmeSeedSql(programmes) {
  const rows = programmes.map((p) => JSON.stringify({
    id: p.id, title: p.title, summary: p.summary, context: p.context, split: p.split, level: p.level,
    days_per_week: p.daysPerWeek, default_weekdays: p.defaultWeekdays, session_minutes: p.sessionMinutes,
    built_around: p.builtAround, is_premium: p.isPremium, source_notes: p.sourceNotes,
    days: p.days.map((d, i) => ({ day_index: i, key: d.key, title: d.title, focus: d.focus, slots: d.slots })),
  }));
  return `-- FITX Workouts v2 (5 of 6): the authored training programmes, published.
-- Generated by scripts/catalog/build-programmes.mjs from src/data/programmes/index.ts; do not edit by hand.
-- Re-running updates the programmes in place and replaces their days. Enrolments are untouched.

drop table if exists fitx_programme_seed;
create temporary table fitx_programme_seed as
select value as programme from jsonb_array_elements($programmes$[
${rows.join(",\n")}
]$programmes$::jsonb);

insert into public.training_programmes (id, title, summary, context, split, level, days_per_week, default_weekdays,
  session_minutes, built_around, is_premium, status, source_notes)
select programme->>'id', programme->>'title', programme->>'summary', programme->>'context', programme->>'split',
  programme->>'level', (programme->>'days_per_week')::smallint,
  array(select jsonb_array_elements_text(programme->'default_weekdays')::smallint),
  (programme->>'session_minutes')::smallint,
  array(select jsonb_array_elements_text(programme->'built_around')),
  (programme->>'is_premium')::boolean, 'published', programme->>'source_notes'
from fitx_programme_seed
on conflict (id) do update set
  title = excluded.title, summary = excluded.summary, context = excluded.context, split = excluded.split,
  level = excluded.level, days_per_week = excluded.days_per_week, default_weekdays = excluded.default_weekdays,
  session_minutes = excluded.session_minutes, built_around = excluded.built_around, is_premium = excluded.is_premium,
  source_notes = excluded.source_notes, updated_at = now();

delete from public.training_programme_days d
using fitx_programme_seed s
where d.programme_id = s.programme->>'id';

insert into public.training_programme_days (programme_id, day_index, key, title, focus, slots)
select s.programme->>'id', (day->>'day_index')::smallint, day->>'key', day->>'title',
  array(select jsonb_array_elements_text(day->'focus')), day->'slots'
from fitx_programme_seed s
cross join lateral jsonb_array_elements(s.programme->'days') as day;

drop table fitx_programme_seed;
`;
}
if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const sql = programmeSeedSql(PROGRAMMES);
  if (process.argv.includes("--check")) {
    const same = readFileSync(PROGRAMME_SEED_MIGRATION, "utf8") === sql;
    console.log(same ? "Programme seed is up to date." : "Programme seed is out of date: run node scripts/catalog/build-programmes.mjs");
    if (!same) process.exitCode = 1;
  } else {
    writeFileSync(PROGRAMME_SEED_MIGRATION, sql);
    console.log(`Wrote ${path.relative(ROOT, PROGRAMME_SEED_MIGRATION)}`);
  }
}
