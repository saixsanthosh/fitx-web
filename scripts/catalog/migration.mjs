// Renders supabase/migrations/20261118130010_fitx_exercise_catalog_cleanup.sql from loadCatalog() rows.
// The output depends only on the rows, so the committed file can be compared with a fresh render.
import { loadCatalog, readUpstreamSnapshot, summarizeCatalog, validateCatalog } from "./catalog.mjs";
import { REPO_ROOT, sourceMigrations } from "./source.mjs";

export const MIGRATION_PATH = "supabase/migrations/20261118130010_fitx_exercise_catalog_cleanup.sql";
const DOLLAR_TAG = "$catalog$";

/** Column order of the data rows; `name` is for review only and is not written. */
export const MIGRATION_COLUMNS = [
  ["id", "text"], ["name", null], ["primary_muscle", "text"], ["category", "text"], ["mechanic", "text"], ["muscle_group", "text"],
  ["prescription_type", "text"], ["default_duration_seconds", "integer"], ["recommended_sets", "smallint"],
  ["reps_min", "smallint"], ["reps_max", "smallint"], ["rest_seconds", "smallint"], ["required_equipment", "text[]"],
  ["locations", "text[]"], ["alternatives", "text[]"], ["source_ref", "text"], ["merged_into", "text"],
];

const UPDATED = MIGRATION_COLUMNS.map(([column]) => column).filter((column) => !["id", "name", "merged_into"].includes(column));

function dataRow(row) {
  return JSON.stringify(Object.fromEntries(MIGRATION_COLUMNS.map(([column]) => [column, row[column]])));
}

function countLine(label, counts) {
  return `--   ${label}: ${Object.entries(counts).map(([key, value]) => `${key} ${value}`).join(", ")}`;
}

/** The migration text. `sources` lists the migration files the catalogue was read from. */
export function renderMigration(rows, { sources, upstreamSnapshot = false }) {
  const json = `[\n${rows.map(dataRow).join(",\n")}\n]`;
  if (json.includes(DOLLAR_TAG)) throw new Error(`The catalogue data contains ${DOLLAR_TAG}`);
  const summary = summarizeCatalog(rows);
  const merges = rows.filter((row) => row.merged_into);
  const [starterFile, ...importFiles] = sources;
  const columnList = MIGRATION_COLUMNS.filter(([, type]) => type).map(([column, type]) => `${column} ${type}`);
  const header = [
    "-- FITX Workouts v2 (2 of 6): the exercise catalogue clean-up.",
    "-- GENERATED by scripts/catalog/build-catalog.mjs. Do not edit by hand: change scripts/catalog/ (rules.mjs,",
    "-- curation.mjs) and run `node scripts/catalog/build-catalog.mjs`. scripts/catalog/catalog.test.mjs fails when",
    "-- this file differs from what the script generates.",
    "-- Source rows, read from the migrations that created them:",
    `--   ${starterFile} (the 30 FITX starter exercises);`,
    `--   ${importFiles[0]} ... ${importFiles.at(-1)}`,
    `--   (${importFiles.length} files, Free Exercise DB, Unlicense, pinned f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5).`,
    upstreamSnapshot
      ? "-- Upstream categories and mechanics come from scripts/catalog/upstream-classification.json where present."
      : "-- Categories and mechanics come from the rules and curation (no upstream classification snapshot).",
    "--",
    "-- Runs after 20261118130000 (which adds the columns). Plain SQL, safe to run more than once; rows are",
    "-- matched by id and ids missing from the database are skipped.",
    `--   1. Fills the Workouts v2 columns of all ${summary.rows} catalogue rows and sets catalog_version = 1.`,
    `--   2. Hides the ${merges.length} imported rows that duplicate a starter row: is_active = false and`,
    "--      merged_into = the starter id, provided that row exists (other rows keep is_active and merged_into).",
    "--   3. Points saved plan, session and personal-record rows at the surviving id; recorded exercise names",
    "--      are left as they are.",
    "-- Derived values:",
    countLine("category", summary.category),
    countLine("mechanic", summary.mechanic),
    countLine("prescription", summary.prescription),
    countLine("location", summary.location),
    "--   merged (duplicate -> survivor):",
    ...merges.map((row) => `--     ${row.id} -> ${row.merged_into}`),
  ];
  return [
    ...header,
    "",
    "update public.exercise_library as e",
    `set ${UPDATED.map((column) => `${column} = c.${column}`).join(",\n    ")},`,
    "    merged_into = coalesce(survivor.id, e.merged_into),",
    "    is_active = case when survivor.id is null then e.is_active else false end,",
    "    catalog_version = 1",
    `from jsonb_to_recordset(${DOLLAR_TAG}`,
    json,
    `${DOLLAR_TAG}::jsonb) as c (`,
    `  ${columnList.join(",\n  ")}`,
    ")",
    "left join public.exercise_library as survivor on survivor.id = c.merged_into",
    "where e.id = c.id;",
    "",
    "-- Saved plans, workout sessions and personal records follow a merged duplicate to its survivor.",
    ...["workout_plan_exercises", "workout_session_exercises", "personal_records"].flatMap((table) => [
      `update public.${table} as t`,
      "set exercise_id = e.merged_into",
      "from public.exercise_library as e",
      "where t.exercise_id = e.id and e.merged_into is not null;",
      "",
    ]),
  ].join("\n");
}

/**
 * The migration text for the current sources, rules and curation. `upstream` as in loadCatalog().
 * Throws when the catalogue breaks a check, so a bad catalogue is never written.
 */
export function generateMigration({ root = REPO_ROOT, upstream } = {}) {
  const rows = loadCatalog({ root, upstream });
  const problems = validateCatalog(rows);
  if (problems.length) throw new Error(`The catalogue has ${problems.length} problem(s):\n${problems.join("\n")}`);
  const upstreamSnapshot = upstream === undefined ? readUpstreamSnapshot(root) !== null : Boolean(upstream);
  return { rows, text: renderMigration(rows, { sources: sourceMigrations(root), upstreamSnapshot }) };
}
