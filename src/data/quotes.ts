export const QUOTE_THEMES: readonly QuoteTheme[] = ["discipline", "consistency", "strength", "mind", "growth", "recovery"];

export const QUOTES: readonly Quote[] = QUOTE_THEMES.flatMap((theme) =>
  LINES[theme].map((text, index) => ({
    id: `${PREFIX[theme]}-${String(index + 1).padStart(3, "0")}`,
    text,
    author: null,
    source: null,
    theme,
    scene: THEME_SCENES[theme][index % 2],
  })),
);

const BY_ID = new Map(QUOTES.map((quote) => [quote.id, quote]));

/** The quote with this id, or null (an id the database knows but this build does not). */
export function quoteById(id: string | null | undefined): Quote | null {
  return id ? BY_ID.get(id) ?? null : null;
}
